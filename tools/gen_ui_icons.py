def svg(grid: list[str]) -> str:
    rects = []
    for y, row in enumerate(grid[:H]):
        for x, ch in enumerate(row[:W]):
            if ch == ".":
                continue
            color = {"#": MAIN, "+": ACCENT, "o": DARK}.get(ch)
            if color is None:
                continue
            rects.append(f'<rect x="{x}" y="{y}" width="1" height="1" fill="{color}"/>')
    return ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 16 16" '
            'width="16" height="16" shape-rendering="crispEdges">'
            + "".join(rects) + "</svg>\n")


def main():
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    out = os.path.join(root, "static", "icons", "ui")
    os.makedirs(out, exist_ok=True)
    n = 0
    for name, grid in ICONS.items():
        # 容错:网格是手画的,容易多一个点/少一行 → 补齐或截断,并提示哪几行被改过
        fixed, bad = [], []
        for i, row in enumerate(grid[:H]):
            if len(row) != W:
                bad.append(i)
                row = (row + "." * W)[:W]
            fixed.append(row)
        while len(fixed) < H:
            fixed.append("." * W)
        if bad:
            print(f"  ⚠ {name}: 行 {bad} 长度不是 {W},已自动补齐/截断")
        grid = fixed
        with open(os.path.join(out, name + ".svg"), "w", encoding="utf-8") as f:
            f.write(svg(grid))
        n += 1
    print(f"✓ 生成 {n} 枚 UI 像素图标 → static/icons/ui/")
    print("  " + ", ".join(sorted(ICONS)))


if __name__ == "__main__":
    main()
